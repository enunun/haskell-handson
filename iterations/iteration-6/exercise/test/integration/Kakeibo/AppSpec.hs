module Kakeibo.AppSpec (spec) where

import Kakeibo.App (run)
import Test.Hspec

spec :: Spec
spec = do
  describe "run" $ do
    it "支出を1件ずつ表示し，費目別の小計と合計を表示する" $
      run ["食費:1200", "交通費:350"]
        `shouldBe` Right
          [ "食費 1,200円",
            "交通費 350円",
            "費目別:",
            "  食費 1,200円",
            "  交通費 350円",
            "合計: 1,550円"
          ]
    it "同じ費目の支出は，費目別の小計でまとめる" $
      run ["食費:1200", "交通費:350", "食費:350"]
        `shouldBe` Right
          [ "食費 1,200円",
            "交通費 350円",
            "食費 350円",
            "費目別:",
            "  食費 1,550円",
            "  交通費 350円",
            "合計: 1,900円"
          ]
    it "費目のない金額は，その他として表示する" $
      run ["1200", "350", "800"]
        `shouldBe` Right
          [ "その他 1,200円",
            "その他 350円",
            "その他 800円",
            "費目別:",
            "  その他 2,350円",
            "合計: 2,350円"
          ]
    it "引数がなければ，支出がないことを表示する" $
      run [] `shouldBe` Right ["支出はありません"]
    it "金額が正の整数でない引数があれば，エラーメッセージを返す" $
      run ["食費:1200", "交通費:abc"]
        `shouldBe` Left "金額は正の整数で書いてください: 交通費:abc"
    it "費目別の小計は，金額の大きい順に表示する" $
      run ["食費:350", "交通費:1200"]
        `shouldBe` Right
          [ "食費 350円",
            "交通費 1,200円",
            "費目別:",
            "  交通費 1,200円",
            "  食費 350円",
            "合計: 1,550円"
          ]
